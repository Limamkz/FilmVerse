function find_content(string $id): ?array
{
    global $catalog;

    foreach ($catalog as $item) {
        if ($item['id'] === $id) {
            return $item;
        }
    }

    return null;
}
function user_favorites(): array
{
    if (!logged_in()) {
        return [];
    }

    $statement = db()->prepare('SELECT content_id FROM favoritos WHERE usuario_id = ?');
    $statement->execute([$_SESSION['user_id']]);

    return array_column($statement->fetchAll(), 'content_id');
}
